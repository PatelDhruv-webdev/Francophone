const globalsPath = join(process.cwd(), 'src/app/globals.css')
const existing = readFileSync(globalsPath, 'utf8')

// Remove any previous auto-generated block
const withoutGenerated = existing.replace(
  /\/\* AUTO-GENERATED[\s\S]*?(?=@layer base \{[\s\S]*?html)/,
  '',
)

// Prepend the new generated block after the first @import/@tailwind line
const firstLayerIndex = withoutGenerated.indexOf('@layer base {')
const before = withoutGenerated.slice(0, firstLayerIndex)
const after = withoutGenerated.slice(firstLayerIndex)

writeFileSync(globalsPath, before + cssVars + '\n' + after)
console.log('✓ CSS variables written to src/app/globals.css')
