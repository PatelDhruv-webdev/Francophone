#!/usr/bin/env tsx
/**
 * Reads the active theme and writes CSS variable overrides into globals.css.
 * Run after any theme change: `npx tsx scripts/generate-css-vars.ts`
 *
 * This is the bridge between src/design-system/ (JS) and the CSS/shadcn layer.
 * Changing the theme file → run this script → entire app re-themes.
 */
import { writeFileSync, readFileSync } from 'fs'
import { join } from 'path'

// Inline the theme values to avoid ESM import issues in a script
